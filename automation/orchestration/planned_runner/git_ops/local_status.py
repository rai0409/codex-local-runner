def _run_git(
    repo_path: str,
    args: list[str],
    *,
    timeout_seconds: float | None = None,
) -> subprocess.CompletedProcess[str]:
    return subprocess.run(
        ["git", "-C", repo_path, *args],
        text=True,
        capture_output=True,
        timeout=timeout_seconds,
    )

def _collect_changed_tracked_files(
    repo_path: str,
    *,
    timeout_seconds: float | None = 10,
) -> tuple[bool, list[str]]:
    try:
        status_short_cmd = _run_git(
            repo_path,
            ["status", "--short", "--untracked-files=no"],
            timeout_seconds=timeout_seconds,
        )
    except (OSError, subprocess.TimeoutExpired):
        return False, []
    if status_short_cmd.returncode != 0:
        return False, []
    changed = sorted(
        {
            _parse_git_status_path(line)
            for line in (status_short_cmd.stdout or "").splitlines()
            if line.strip() and _parse_git_status_path(line)
        }
    )
    return True, changed

def _parse_git_status_path(line: str) -> str:
    if len(line) < 4:
        return ""
    raw_path = line[3:].strip()
    if not raw_path:
        return ""
    if " -> " in raw_path:
        _, rhs = raw_path.split(" -> ", 1)
        raw_path = rhs.strip()
    if raw_path.startswith('"') and raw_path.endswith('"') and len(raw_path) >= 2:
        raw_path = raw_path[1:-1]
    return raw_path

def _resolve_current_branch(repo_path: str, *, command_summary: dict[str, Any]) -> str:
    branch_result = _run_git(repo_path, ["rev-parse", "--abbrev-ref", "HEAD"])
    command_summary["branch_rc"] = branch_result.returncode
    if branch_result.returncode != 0:
        return ""
    branch_name = _normalize_text(branch_result.stdout, default="")
    if branch_name == "HEAD":
        return ""
    return branch_name

def _collect_prompt357_local_git_diff_changed_files(
    *,
    execution_repo_path: str,
) -> list[str]:
    repo_path = _normalize_text(execution_repo_path, default="")
    if not repo_path:
        return []
    repo_dir = Path(repo_path)
    if not repo_dir.exists() or not repo_dir.is_dir():
        return []

    changed_files: set[str] = set()
    for command in (["diff", "--name-only"], ["diff", "--cached", "--name-only"]):
        result = _run_git(repo_path, command)
        if result.returncode != 0:
            continue
        for raw_line in (result.stdout or "").splitlines():
            path = raw_line.strip()
            if path:
                changed_files.add(path)

    return _normalize_string_list(changed_files, sort_items=True)

def _prompt460_git_status_files(
    *,
    repo_path: str,
) -> tuple[bool, list[str], list[str]]:
    try:
        status_result = _run_git(
            repo_path,
            ["status", "--short"],
            timeout_seconds=10.0,
        )
    except (OSError, subprocess.TimeoutExpired):
        return False, [], []
    if status_result.returncode != 0:
        return False, [], []
    changed_files: set[str] = set()
    untracked_files: set[str] = set()
    for line in (status_result.stdout or "").splitlines():
        if not line.strip():
            continue
        path = _parse_git_status_path(line)
        if not path:
            continue
        if line.startswith("?? "):
            untracked_files.add(path)
        else:
            changed_files.add(path)
    return True, sorted(changed_files), sorted(untracked_files)

def _prompt483_untracked_files(*, repo_path: str) -> list[str]:
    if not repo_path:
        return []
    try:
        completed = subprocess.run(
            ["git", "ls-files", "--others", "--exclude-standard"],
            cwd=repo_path,
            capture_output=True,
            text=True,
            check=False,
            timeout=30,
        )
    except (OSError, subprocess.TimeoutExpired):
        return []
    if completed.returncode != 0:
        return []
    return _normalize_string_list(completed.stdout.splitlines(), sort_items=False)
